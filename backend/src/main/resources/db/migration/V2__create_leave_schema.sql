CREATE TABLE leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_profile_id BIGINT NOT NULL,
    leave_type VARCHAR(30) NOT NULL,
    entitled_days INTEGER NOT NULL,
    used_days INTEGER NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_leave_balance_employee_type UNIQUE (employee_profile_id, leave_type),
    CONSTRAINT fk_leave_balance_profile FOREIGN KEY (employee_profile_id) REFERENCES employee_profiles(id),
    CONSTRAINT ck_leave_balance_entitled CHECK (entitled_days >= 0),
    CONSTRAINT ck_leave_balance_used CHECK (used_days >= 0)
);

CREATE TABLE leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_profile_id BIGINT NOT NULL,
    leave_type VARCHAR(30) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    leave_days INTEGER NOT NULL,
    reason VARCHAR(1000),
    status VARCHAR(20) NOT NULL,
    submitted_at TIMESTAMP NOT NULL,
    decided_at TIMESTAMP,
    decision_maker_id BIGINT,
    decision_remarks VARCHAR(1000),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_leave_request_profile FOREIGN KEY (employee_profile_id) REFERENCES employee_profiles(id),
    CONSTRAINT fk_leave_request_decider FOREIGN KEY (decision_maker_id) REFERENCES users(id),
    CONSTRAINT ck_leave_request_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_leave_request_days CHECK (leave_days > 0)
);

CREATE INDEX idx_leave_request_employee ON leave_requests(employee_profile_id, submitted_at);
CREATE INDEX idx_leave_request_review ON leave_requests(status, employee_profile_id);
