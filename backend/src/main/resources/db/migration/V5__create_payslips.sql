CREATE TABLE payslips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_profile_id BIGINT NOT NULL,
    pay_period_start DATE NOT NULL,
    pay_period_end DATE NOT NULL,
    issued_at TIMESTAMP NOT NULL,
    storage_key VARCHAR(80) NOT NULL UNIQUE,
    CONSTRAINT fk_payslip_employee FOREIGN KEY (employee_profile_id) REFERENCES employee_profiles(id),
    CONSTRAINT uk_payslip_employee_period UNIQUE (employee_profile_id, pay_period_start),
    CONSTRAINT chk_payslip_period CHECK (pay_period_end >= pay_period_start)
);

CREATE INDEX idx_payslip_employee_period ON payslips(employee_profile_id, pay_period_start);
