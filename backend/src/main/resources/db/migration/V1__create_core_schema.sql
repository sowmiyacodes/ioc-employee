CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    active BOOLEAN NOT NULL,
    account_non_locked BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE INDEX idx_user_username ON users(username);
CREATE INDEX idx_user_email ON users(email);

CREATE TABLE employee_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    employee_id VARCHAR(30) NOT NULL UNIQUE,
    legal_name VARCHAR(150) NOT NULL,
    department VARCHAR(100) NOT NULL,
    designation VARCHAR(100) NOT NULL,
    joining_date DATE NOT NULL,
    manager_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_profile_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_profile_manager FOREIGN KEY (manager_id) REFERENCES users(id)
);

CREATE TABLE employee_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_profile_id BIGINT NOT NULL UNIQUE,
    residential_street VARCHAR(200) NOT NULL,
    residential_city VARCHAR(100) NOT NULL,
    residential_state VARCHAR(100) NOT NULL,
    residential_postal_code VARCHAR(20) NOT NULL,
    residential_country VARCHAR(100) NOT NULL,
    mailing_street VARCHAR(200) NOT NULL,
    mailing_city VARCHAR(100) NOT NULL,
    mailing_state VARCHAR(100) NOT NULL,
    mailing_postal_code VARCHAR(20) NOT NULL,
    mailing_country VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_address_profile FOREIGN KEY (employee_profile_id) REFERENCES employee_profiles(id)
);
